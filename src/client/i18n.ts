// Formatar datas para o padrão americano MM/DD/YYYY
export function formatAmericanDate(dStr: string): string {
  if (!dStr) return '';
  if (/^\d{2}\/\d{2}\/\d{4}$/.test(dStr)) return dStr;
  if (/^\d{4}-\d{2}-\d{2}$/.test(dStr)) {
    const [year, month, day] = dStr.split('-');
    return `${month}/${day}/${year}`;
  }
  return dStr;
}

